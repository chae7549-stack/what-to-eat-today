def validate():
    """id 중복·별칭 중복 점검 (build 에서 호출)."""
    from collections import defaultdict
    errs = []
    ids = [i["id"] for i in ITEMS]
    dup = {x for x in ids if ids.count(x) > 1}
    if dup:
        errs.append(f"id 중복: {sorted(dup)}")
    owner = defaultdict(list)
    for item in ITEMS:
        for a in item["aliases"] + [item["label"]]:
            owner[a].append(item["id"])
    clash = {a: v for a, v in owner.items() if len(set(v)) > 1}
    if clash:
        errs.append(f"별칭 중복: {clash}")
    bad_group = [i["id"] for i in ITEMS if i["group"] not in GROUPS]
    if bad_group:
        errs.append(f"그룹 오류: {bad_group}")
    return errs


if __name__ == "__main__":
    errs = validate()
    print(f"재료 {len(ITEMS)}종 · 그룹 {len(GROUPS)}개")
    from collections import Counter
    print(dict(Counter(i["group"] for i in ITEMS)))
    print("\n".join(errs) if errs else "검사 통과")
