def bracket(pmin, pmax):
    if pmax <= 10000:
        return "under10k"
    if pmin < 20000:
        return "10to20k"
    return "over20k"


def price_label(pmin, pmax):
    def w(n):
        return f"{n:,}"
    return f"{w(pmin)}원" if pmin == pmax else f"{w(pmin)}~{w(pmax)}원"


def budget_of(pmin, pmax):
    b = bracket(pmin, pmax)
    return {"under10k": "low", "10to20k": "mid", "over20k": "high"}[b]


def rows():
    """빌드용 레코드."""
    out, seen = [], set()
    for m in MENUS:
        if m["name"] in seen:
            raise SystemExit("배달 메뉴 이름 중복: " + m["name"])
        seen.add(m["name"])
        out.append({
            "name": m["name"], "emoji": m["emoji"], "cat": m["cat"],
            "price": price_label(m["pmin"], m["pmax"]),
            "priceMin": m["pmin"], "priceMax": m["pmax"],
            "bracket": bracket(m["pmin"], m["pmax"]),
            "budget": budget_of(m["pmin"], m["pmax"]),
            "moods": m["moods"], "tip": m["tip"], "note": m["note"],
        })
    return out


